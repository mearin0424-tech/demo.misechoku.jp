<?php

/*
|--------------------------------------------------------------------------
| LLM (Large Language Model) 設定
|--------------------------------------------------------------------------
|
| ミセチョクの「AIコンシェルジュ」で使う対話 LLM の接続設定。
|
| OpenAI 互換の Chat Completions API を話せるプロバイダなら差し替え可能：
|   - Groq（無料枠が広く、Llama 3.3 / Qwen 2.5 系がホストされている・推奨）
|       endpoint: https://api.groq.com/openai/v1/chat/completions
|       model:    llama-3.3-70b-versatile / qwen-2.5-32b-instruct 等
|   - Together AI, OpenRouter 等の OSS モデルホスティング
|   - Ollama（ローカル / セルフホスト）
|       endpoint: http://localhost:11434/v1/chat/completions
|       model:    qwen2.5:7b-instruct / llama3.1:8b-instruct 等
|
| provider = 'template' の場合は既存のテンプレ実装（AiChatTemplateService）で
| 動作する。API キー未設定・接続失敗時にも自動でテンプレへフォールバックする。
|
*/

return [

    /*
    |----------------------------------------------------------------------
    | プロバイダ
    |----------------------------------------------------------------------
    |
    | 'template'      : LLM を呼ばず、既存のテンプレ返答のみ（デフォルト）
    | 'openai_compat' : OpenAI 互換エンドポイント（Groq / Together / OpenRouter / Ollama）
    |
    */
    'provider' => env('LLM_PROVIDER', 'template'),

    /*
    |----------------------------------------------------------------------
    | エンドポイント URL (chat/completions)
    |----------------------------------------------------------------------
    */
    'endpoint' => env('LLM_ENDPOINT', 'https://api.groq.com/openai/v1/chat/completions'),

    /*
    |----------------------------------------------------------------------
    | API キー
    |----------------------------------------------------------------------
    |
    | Groq: https://console.groq.com/keys （無料）
    | Ollama: 空でよい
    |
    */
    'api_key' => env('LLM_API_KEY', ''),

    /*
    |----------------------------------------------------------------------
    | モデル名
    |----------------------------------------------------------------------
    |
    | Groq 推奨:
    |   - 'llama-3.3-70b-versatile' （日本語○、応答質高）
    |   - 'qwen-2.5-32b-instruct'   （日本語◎、少し重い）
    |   - 'llama-3.1-8b-instant'    （日本語△、超高速）
    | Ollama 推奨:
    |   - 'qwen2.5:7b-instruct'
    |   - 'llama3.1:8b-instruct'
    |
    */
    'model' => env('LLM_MODEL', 'llama-3.3-70b-versatile'),

    /*
    |----------------------------------------------------------------------
    | 生成パラメータ
    |----------------------------------------------------------------------
    */
    'max_tokens'  => (int) env('LLM_MAX_TOKENS', 350),
    'temperature' => (float) env('LLM_TEMPERATURE', 0.75),
    'top_p'       => (float) env('LLM_TOP_P', 0.95),

    /*
    |----------------------------------------------------------------------
    | リクエストタイムアウト（秒）
    |----------------------------------------------------------------------
    |
    | Groq は LPU で高速（数百 ms〜数秒）だが、モバイル回線 + サーバ経由も
    | 考慮して 15 秒を既定に。Ollama をローカルで叩く場合はもっと短くて可。
    |
    */
    'timeout' => (int) env('LLM_TIMEOUT', 15),

    /*
    |----------------------------------------------------------------------
    | 会話履歴に載せる過去ターン数の上限
    |----------------------------------------------------------------------
    |
    | 直近 N ターン (user/assistant セットで N 回) をシステムメッセージの後ろに
    | 積む。あまり長いと token を食うだけなので 6 前後が目安。
    |
    */
    'history_turns' => (int) env('LLM_HISTORY_TURNS', 6),

    /*
    |----------------------------------------------------------------------
    | エラー時にテンプレへフォールバックするか
    |----------------------------------------------------------------------
    |
    | true の場合、LLM のレスポンスが失敗しても AiChatTemplateService の
    | 返答を代わりに返す（体感でエラー画面を出さない）。
    |
    */
    'fallback_to_template' => (bool) env('LLM_FALLBACK', true),

];
